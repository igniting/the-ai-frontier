// The superoptimizer: mines the WebAssembly Lumen 2 emits for windows of
// straight-line code, searches for a cheaper equivalent of each, proves every
// candidate for all inputs, generalizes constants where it can, and writes
// the rules the compiler applies (compiler/rules.js) with a report
// (superopt/RULES.md, superopt/rules.json).
//
//   node superopt/search.js [--fuzz N] [--seconds S]

import { writeFileSync } from 'node:fs';
import { compileCorpus, mine } from './corpus.js';
import { synthesize, generalize, cost } from './synth.js';
import { peephole } from './peephole.js';

const arg = (name, d) => { const i = process.argv.indexOf(name); return i >= 0 ? Number(process.argv[i + 1]) : d; };
const FUZZ = arg('--fuzz', 60);
const SECONDS = arg('--seconds', 240);
const here = (p) => new URL(p, import.meta.url);
const show = (code) => code.map(([op, a]) => (a === undefined ? op.replace(/^(i32|i64)\./, '$1.') : `${op.replace('.const', '').replace('local.get', '')}${op === 'local.get' ? a : ` ${a}`}`.trim())).join('  ');

const t0 = performance.now();
const deadline = t0 + SECONDS * 1000;
const modules = compileCorpus({ fuzz: FUZZ });
const rules = [];
const tried = new Set();
const log = { rounds: 0, windows: 0, searches: 0 };

// Two rounds: the second mines the corpus after rewriting it with the first round's rules.
for (let round = 1; round <= 2 && performance.now() < deadline; round++) {
  log.rounds = round;
  const corpus = round === 1 ? modules : modules.map((m) => ({ ...m, funcs: m.funcs.map((f) => ({ ...f, body: peephole(f.body, { rules }) })) }));
  const windows = mine(corpus, { maxLen: 7, minCount: 2 });
  log.windows += windows.length;
  for (const w of windows) {
    if (performance.now() > deadline) break;
    if (tried.has(w.key)) continue;
    tried.add(w.key);
    // Skip windows another rule already rewrites.
    if (peephole(w.code.map(([op, a]) => [op, op === 'local.get' ? a : a]), { rules }).length < w.code.length) continue;
    const big = w.code.length >= 6;
    log.searches++;
    let found = synthesize(w, { maxDepth: Math.min(w.code.length - 1, 4), maxStates: 60000, deadline: Math.min(deadline, performance.now() + 4000) });
    if (!found && big) found = synthesize(w, { maxDepth: 5, maxStates: 40000, focused: true, deadline: Math.min(deadline, performance.now() + 15000) });
    if (!found) continue;
    let general = generalize(w, found.code);
    // A rule that holds only for these constants: look for one that holds for all of them.
    if (!general && w.code.some(([op, a]) => op.endsWith('.const') && (BigInt(a) < -1n || BigInt(a) > 1n))) {
      const s = synthesize(w, { maxDepth: Math.min(w.code.length - 1, 5), maxStates: 40000, focused: w.code.length >= 6, symbolic: true, deadline: Math.min(deadline, performance.now() + 15000) });
      if (s && s.code.length <= found.code.length) general = { lhs: s.lhs, rhs: s.code, ks: s.ks, when: s.when, proof: s.proof };
    }
    const r = general
      ? { lhs: general.lhs, rhs: general.rhs, ks: general.ks, when: general.when, proof: general.proof }
      : { lhs: w.code, rhs: found.code, ks: {}, when: [], proof: found.proof };
    const before = cost(w.code), after = cost(found.code);
    rules.push({
      id: rules.length, ...r, inputs: w.inputs, locals: w.locals, seen: w.seen, round,
      example: { lhs: w.code, rhs: found.code },
      saves: { instructions: before.instructions - after.instructions, bytes: before.bytes - after.bytes },
    });
    console.log(`rule ${rules.length - 1} (seen ${w.seen}): ${show(r.lhs)}  =>  ${show(r.rhs)}${r.when.length ? `   when ${r.when.join(', ')}` : ''}   [${r.proof.structural ? 'structural' : `${r.proof.lemmas} lemmas`}]`);
  }
}
const seconds = (performance.now() - t0) / 1000;

// How often each rule fires on the corpus, rewritten from scratch.
const fired = new Map();
let before = 0, after = 0;
for (const m of modules) for (const f of m.funcs) { before += f.body.length; after += peephole(f.body, { rules, stats: fired }).length; }
for (const r of rules) r.fires = fired.get(r.id) ?? 0;

const strip = ({ example, ...r }) => r;
writeFileSync(here('../compiler/rules.js'), `// Generated by \`node superopt/search.js\`; do not edit. Each rule is proved
// in superopt/RULES.md, and \`node superopt/verify.js\` re-proves them all.
export const RULES = [
${rules.map(({ id, lhs, rhs, when }) => `  ${JSON.stringify({ id, lhs: lhs.map(([op, a]) => (a === undefined ? [op] : [op, a])), rhs: rhs.map(([op, a]) => (a === undefined ? [op] : [op, a])), when })},`).join('\n')}
];
`);
writeFileSync(here('rules.json'), `${JSON.stringify({ generated: 'node superopt/search.js', corpus: { modules: modules.length, fuzz: FUZZ }, ...log, seconds: +seconds.toFixed(1), instructions: { before, after }, rules: rules.map(strip) }, null, 1)}\n`);

const expr = (r) => r.when.length ? ` (when ${r.when.join(', ')})` : '';
const md = `# Rewrite rules found by the Lumen 2 superoptimizer

Generated by \`node superopt/search.js\` from ${modules.length} modules (the
examples, the Schur proof's two programs and ${FUZZ} generated programs):
${log.windows} windows of straight-line code seen at least twice, mined in
${log.rounds} rounds, ${log.searches} searches, ${seconds.toFixed(1)} s.

Every rule was found by enumeration and proved for **all** values of its
inputs, its locals and its symbolic constants \`K\` (subject to the side
conditions shown, which the compiler checks before rewriting), by the SAT
solver in \`superopt/sat.js\`. Each refutation was checked by the independent
proof checker in \`src/rup.js\`. \`node superopt/verify.js\` re-proves them
all; with \`--emit DIR\` it writes each formula and proof in the DIMACS and
DRUP formats that external checkers read.

On the corpus, the rules remove ${before - after} of ${before} instructions
(${((100 * (before - after)) / before).toFixed(2)}%).

Stack code reads left to right: values already on the stack are used
first, \`x0\` is a local, \`K0\` a constant. *Seen* counts the windows in
the corpus the rule was found from; *fires* counts rewrites on the corpus.
*Proof*: \`structural\` means the two circuits were identical, so no search
was needed.

| # | stack code | becomes | seen | fires | saves | proof |
|---|---|---|---|---|---|---|
${rules.map((r) => `| ${r.id} | \`${show(r.lhs)}\` | \`${show(r.rhs) || 'ε'}\`${expr(r)} | ${r.seen} | ${r.fires} | ${r.saves.instructions} | ${r.proof.structural ? 'structural' : `${r.proof.lemmas.toLocaleString('en-US')} lemmas`} |`).join('\n')}
`;
writeFileSync(here('RULES.md'), md);
console.log(`${rules.length} rules, ${log.searches} searches, ${seconds.toFixed(1)} s; corpus ${before} -> ${after} instructions`);
