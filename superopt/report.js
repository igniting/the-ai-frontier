// Turns superopt/rules.json into the compiler's rule table (src/rules.js)
// and a human-readable catalogue (superopt/RULES.md).
//
//   node superopt/report.js [DIR]

import { readFileSync, writeFileSync } from 'node:fs';
import { show, showExpr } from './show.js';

export function writeOutputs(dir = '.') {
  const data = JSON.parse(readFileSync(`${dir}/superopt/rules.json`, 'utf8'));
  const { rules } = data;
  const compact = rules.map(({ id, lhs, rhs, odd, inputs }) => ({ id, inputs, odd, lhs, rhs }));
  writeFileSync(`${dir}/src/rules.js`, `// Generated by superopt/search.js: rewrite rules proved by SAT, with every
// proof checked by an independent RUP checker. See superopt/RULES.md.
// Do not edit by hand; regenerate with \`npm run superopt\`.

export const RULES = [
${compact.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`);

  const esc = (t) => t.replace(/\|/g, '\\|');
  const pre = (r) => r.odd.map((o, i) => (o ? `x${i} odd` : null)).filter(Boolean).join(', ');
  const rows = rules.map((r) => {
    const where = r.origin === 'corpus' ? `${r.seen}` : 'variant';
    const proof = r.proof.trivial ? 'structural' : `${r.proof.lemmas.toLocaleString('en')} lemmas`;
    return `| ${r.id} | \`${esc(show(r.lhs))}\` | \`${esc(show(r.rhs)) || 'ε'}\` | ${esc(showExpr(r.lhs, r.inputs))} ⇒ ${esc(showExpr(r.rhs, r.inputs))}${pre(r) ? ` (${pre(r)})` : ''} | ${where} | ${r.saves.instructions} | ${proof} |`;
  });
  const lemmas = rules.reduce((n, r) => n + r.proof.lemmas, 0);
  writeFileSync(`${dir}/superopt/RULES.md`, `# Discovered rewrite rules

Generated by \`node superopt/search.js\` from ${data.corpus.modules} modules
(the examples plus ${data.corpus.fuzz} random programs): ${data.corpus.windows} distinct windows of
straight-line code seen at least ${data.corpus.minCount} times, ${data.searches} searches, ${data.seconds} s.

Every rule below was found by enumeration, proved for **all** 2^32 values of
each input (and of each symbolic constant \`K\`) by the SAT solver in
\`superopt/sat.js\`, and its refutation proof — ${lemmas.toLocaleString('en')} learned clauses in total —
was checked by the independent RUP checker in \`superopt/rup.js\`.
\`node superopt/verify.js\` re-proves them all from scratch; with \`--emit DIR\`
it also writes each formula and proof as \`rule-N.cnf\` / \`rule-N.drup\`, so they can be
checked by a third party's tool, e.g. \`drat-trim rule-17.cnf rule-17.drup\`
(CI uploads these files as the \`superopt-proofs\` artifact).

*Stack code* reads left to right; \`a\` and \`b\` are values already on the
stack, \`x0\` is a local. *Seen* counts occurrences in the corpus (\`variant\`:
the same rule for another comparison operator). *Proof*: \`structural\` means
the two circuits were identical after hash-consing, so no search was needed.

| # | stack code | becomes | as an expression | seen | saves | proof |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`);
}

if (import.meta.url === `file://${process.argv[1]}`) writeOutputs(process.argv[2] ?? '.');
